async page => {
  page.setDefaultTimeout(10000);
  const origin = __ORIGIN__, checks = [], errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const heading = name => page.getByRole('heading', { name, exact: true });
  const button = name => page.getByRole('button', { name, exact: true });
  try {
    await page.goto(origin + '/multi-step-creation/requests');
    await button('New review request').click();
    await heading('Supplier details').waitFor();
    await page.waitForURL('**/drafts/*/details');
    const detailsURL = page.url(), draftId = new URL(detailsURL).pathname.split('/')[3];
    await page.goto(origin + '/multi-step-creation/drafts/' + draftId + '/scope');
    await heading('Supplier details').waitFor();
    await page.goto(origin + '/multi-step-creation/drafts/' + draftId + '/review');
    await heading('Supplier details').waitFor();
    let releaseSave;
    const saving = new Promise(resolve => { releaseSave = resolve; });
    await page.route('**/drafts/*/details', async route => { await saving; await route.continue(); }, {times: 1});
    const submission = button('Save and leave').click();
    try {
      await button('Saving draft…').waitFor();
      assert(await page.locator('#request-step [data-form-status]').innerText() === 'Saving draft…', 'Submitter-specific pending label is not reflected in feedback');
    } finally { releaseSave(); await submission; }
    await heading('Review requests').waitFor();
    assert((await page.getByRole('region',{name:'Drafts',exact:true}).innerText()).includes('Complete supplier details'), 'Draft collection does not identify the task to resume');
    await page.getByRole('link', { name: 'Untitled supplier review', exact: true }).click();
    await heading('Supplier details').waitFor();
    assert(await page.locator('#entry_supplier').inputValue() === '', 'Partial draft did not resume');
    checks.push('Server enforces step prerequisites; enhanced formnovalidate saves/resumes incomplete drafts');

    await page.locator('#entry_supplier').fill('Northstar Hosting');
    await page.locator('#entry_supplier').press('Enter');
    assert(await page.locator('#entry_owner').evaluate(node => node === document.activeElement), 'Continue must validate and focus missing owner');
    assert(await page.locator('#entry_supplier').inputValue() === 'Northstar Hosting', 'Validation lost supplier');
    await page.locator('#entry_owner').selectOption('alex');
    await page.locator('#entry_supplier').press('Enter');
    await heading('Review scope').waitFor();
    assert(await heading('Review scope').evaluate(node=>node!==document.activeElement), 'A new step must not autofocus its title');
    assert(await page.locator('[aria-invalid="true"]').count() === 0, 'Untouched scope showed errors');
    await page.locator('#entry_purpose').fill('Check access controls and recovery arrangements.');
    await button('Save and go back').click();
    await heading('Supplier details').waitFor();
    assert(await page.locator('#entry_supplier').inputValue() === 'Northstar Hosting', 'Back lost supplier');
    await button('Continue to review scope').click();
    await heading('Review scope').waitFor();
    assert(await page.locator('#entry_purpose').inputValue() === 'Check access controls and recovery arrangements.', 'Back failed to save incomplete scope');
    await page.locator('#entry_due_on').fill('2030-09-30');
    await page.locator('#entry_approach').selectOption('independent');
    await button('Check request').click();
    assert(await page.locator('#entry_assessor').evaluate(node=>node===document.activeElement), 'Conditional required field needs focus');
    await page.locator('#entry_assessor').fill('Independent Assurance Ltd');
    await button('Check request').click();
    await heading('Check review request').waitFor();
    assert(await page.getByText('Independent Assurance Ltd', {exact:true}).count() === 1, 'Review omitted applicable assessor');
    checks.push('Enter validates and advances; Back saves incomplete scope; validation focus is retained without title autofocus');

    await page.waitForURL('**/drafts/*/review');
    const staleReview = await page.context().newPage();
    await staleReview.goto(page.url());
    await page.getByRole('link', {name:'Change supplier details',exact:true}).click();
    await heading('Supplier details').waitFor();
    await page.locator('#entry_supplier').fill('Northstar Managed Hosting');
    await button('Save and return to check').click();
    await heading('Check review request').waitFor();
    assert(await page.getByText('Northstar Managed Hosting',{exact:true}).count()===1, 'Correction missing from check');
    assert(await page.getByText('Independent Assurance Ltd',{exact:true}).count()===1, 'Correction lost other step');
    await staleReview.getByRole('button',{name:'Create review request',exact:true}).click();
    await staleReview.getByRole('heading',{name:'Check the updated draft',exact:true}).waitFor();
    assert(await staleReview.getByText('The draft changed after this check page was opened. No request was created.',{exact:true}).count()===1,'Stale review created without recheck');
    await staleReview.close();
    checks.push('Targeted correction returns to checking, preserves other answers and invalidates stale reviewed revisions');

    await page.getByRole('link',{name:'Change review scope',exact:true}).click();
    await heading('Review scope').waitFor();
    await page.waitForURL('**/drafts/*/scope?return_to=review');
    const staleEditor=await page.context().newPage();
    await staleEditor.goto(page.url());
    const savedPurpose='Review access controls and recovery arrangements.\n\nCheck restoration evidence with the service owner.';
    await page.locator('#entry_purpose').fill(savedPurpose);
    await button('Save and return to check').click();
    await heading('Check review request').waitFor();
    const attemptedPurpose='Check emergency access and its approval trail.\n\nRetain these attempted notes as literal text: <draft>.';
    await staleEditor.locator('#entry_purpose').fill(attemptedPurpose);
    await staleEditor.locator('#entry_approach').selectOption('internal');
    await staleEditor.getByRole('button',{name:'Save and return to check',exact:true}).click();
    await staleEditor.getByRole('heading',{name:'Draft changed in another tab',exact:true}).waitFor();
    const attempted=staleEditor.getByRole('region',{name:'Your attempted answers',exact:true});
    const saved=staleEditor.getByRole('region',{name:'Saved answers',exact:true});
    assert(await attempted.locator('.rich-content p').count()===2 && (await attempted.innerText()).includes('<draft>'), 'Conflict recovery collapsed paragraphs or interpreted source HTML');
    assert(await attempted.locator('draft').count()===0, 'Attempted scope was interpreted as markup');
    assert(!(await attempted.innerText()).includes('Independent Assurance Ltd') && (await saved.innerText()).includes('Independent Assurance Ltd'), 'Conflict comparison ignored each side’s assessment approach');
    assert(await saved.locator('.rich-content p').count()===2 && (await saved.innerText()).includes('Check restoration evidence'), 'Saved scope is absent from recovery');
    const recovered=staleEditor.waitForEvent('popup');
    await staleEditor.getByRole('link',{name:'Open saved step in a new tab',exact:true}).click();
    const recovery=await recovered;
    await recovery.locator('#entry_purpose').waitFor();
    assert(await recovery.locator('#entry_purpose').inputValue()===savedPurpose, 'Stale scope overwrote the saved draft');
    assert((await attempted.innerText()).includes('Retain these attempted notes'), 'Opening recovery removed the attempted scope');
    await recovery.close();await staleEditor.close();
    checks.push('Stale editing retains readable, escaped scope paragraphs and applicable answers; recovery opens separately');

    // Switch branch: an old assessor may remain useful in the draft but must
    // not be represented as applicable in the created internal-review record.
    await page.getByRole('link',{name:'Change review scope',exact:true}).click();
    await page.locator('#entry_approach').selectOption('internal');
    assert(!await page.locator('#entry_assessor').isVisible(),'Inapplicable assessor still visible with enhancement');
    await button('Save and return to check').click();
    await heading('Check review request').waitFor();
    assert(await page.getByText('Independent Assurance Ltd',{exact:true}).count()===0,'Inapplicable assessor included in check');
    await page.getByRole('link',{name:'Review scenarios',exact:true}).click();
    await heading('Review request scenarios').waitFor();
    await button('Fail next creation once').click();
    await page.getByText('The next creation attempt will fail once. The draft will be retained.',{exact:true}).waitFor();
    const createData=await page.locator('#create-request').evaluate(form=>Object.fromEntries(new FormData(form)));
    await button('Create review request').click();
    await page.getByText('The service is unavailable. No request was created. Your reviewed answers are retained; try again.',{exact:true}).waitFor();
    assert(await page.locator('[data-result][data-tone="error"]').evaluate(node=>node===document.activeElement),'Failed creation must focus recovery feedback');
    await button('Create review request').click();
    await heading('Review request created').waitFor();
    await page.waitForURL('**/requests/*');
    const recordURL=page.url();
    assert(await page.getByText('Northstar Managed Hosting',{exact:true}).count()>=1,'Created record uses incorrect answers');
    assert(await page.getByText('Independent Assurance Ltd',{exact:true}).count()===0,'Created internal record leaked hidden assessor');
    const duplicate=await page.request.post(origin+'/multi-step-creation/requests',{form:createData});
    assert(duplicate.ok() && duplicate.url()===recordURL,'Creation replay failed to reconcile existing result');
    await page.goto(detailsURL);
    await heading('Review request created').waitFor();
    await page.getByRole('link',{name:'View all review requests',exact:true}).click();
    await heading('Review requests').waitFor();
    assert(await page.getByRole('link',{name:/^RR-/}).count()===1,'Creation retry made duplicate records');
    checks.push('Branch changes omit inapplicable data; failed creation retries once; duplicate and old-draft requests reconcile');

    const nativeContext=await page.context().browser().newContext({javaScriptEnabled:false});
    const native=await nativeContext.newPage();
    const inaccessible=await native.goto(detailsURL);
    assert(inaccessible.status()===410,'Another browser session accessed this draft');
    await native.getByRole('heading',{name:'Draft unavailable',exact:true}).waitFor();
    await native.getByRole('link',{name:'Return to Review requests',exact:true}).click();
    await native.getByRole('button',{name:'New review request',exact:true}).click();
    await native.getByRole('button',{name:'Save and leave',exact:true}).click();
    await native.getByRole('link',{name:'Untitled supplier review',exact:true}).click();
    await native.locator('#entry_supplier').fill('Native supplier');
    await native.locator('#entry_owner').selectOption('sam');
    await native.locator('#entry_supplier').press('Enter');
    await native.locator('#entry_purpose').fill('Check recovery plans.');
    await native.locator('#entry_due_on').fill('2030-10-01');
    await native.locator('#entry_approach').selectOption('independent');
    await native.getByRole('button',{name:'Check request',exact:true}).click();
    await native.locator('#entry_assessor[aria-invalid="true"]').waitFor();
    assert(await native.locator('#entry_purpose').inputValue()==='Check recovery plans.','Native validation lost scope');
    await native.locator('#entry_assessor').fill('Native independent assessor');
    const scopeURL=await native.locator('#request-step').evaluate(form=>form.action);
    for (const due_on of ['20301001','2030-10-01T10:00','0000-10-01']) {
      const values=await native.locator('#request-step').evaluate(form=>Object.fromEntries(new FormData(form)));
      const rejected=await native.request.post(scopeURL,{form:{...values,'entry[due_on]':due_on,intent:'continue'}});
      assert(rejected.status()===422 && (await rejected.text()).includes('Review due date must be a valid calendar date.'), 'Date-only request field accepted an unsupported calendar representation: '+due_on);
      await native.goto(scopeURL);
    }
    await native.locator('#entry_due_on').fill('2030-10-01');
    await native.locator('#entry_assessor').press('Enter');
    await native.getByRole('link',{name:'Change supplier details',exact:true}).click();
    await native.locator('#entry_supplier').fill('Native supplier corrected');
    await native.getByRole('button',{name:'Save and return to check',exact:true}).click();
    await native.getByRole('button',{name:'Create review request',exact:true}).click();
    await native.getByRole('heading',{name:'Review request created',exact:true}).waitFor();
    await nativeContext.close();
    checks.push('Draft references are session-isolated; native partial saving, strict calendar dates, conditional validation, correction and creation work');
    assert(errors.length===0,errors.join('\n'));
    return {passed:true,checks};
  } catch(error) { throw new Error(JSON.stringify({checks,url:page.url(),errors,content:await page.locator('main').innerText(),error:error.message})); }
}
