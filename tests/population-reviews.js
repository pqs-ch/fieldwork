async page => {
  const origin = __ORIGIN__;
  const checks = [];
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.setDefaultTimeout(10000);
  await page.context().clearCookies();
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const post = async (path, body) => page.evaluate(async ({path, body}) => {
    const token = document.querySelector('meta[name="csrf-token"]').content;
    const response = await fetch(path, {method: 'POST', headers: {'X-CSRF-Token': token, 'Content-Type': 'application/x-www-form-urlencoded'}, body: new URLSearchParams(body)});
    return {status: response.status, text: await response.text()};
  }, {path, body});
  const scenario = action => post('/population-review/scenarios', {scenario: action});
  const formValues = () => page.locator('#review-entry').evaluate(form => [...new FormData(form).entries()]);
  const formReady = () => page.locator('#review-entry[data-form-mode="create"]').waitFor();
  const outcome = () => page.locator('[name="review_entry[choice]"]:checked');
  const choose = value => page.locator(`[name="review_entry[choice]"][value="${value}"]`).check();
  const count = (target, label) => target.locator('.review-counts > div').filter({has:target.getByText(label,{exact:true})}).getByRole('definition').innerText();
  const basis = () => page.getByLabel('Assessment basis', {exact:true});
  const save = () => page.getByRole('button', {name:'Save assessment',exact:true});
  const saved = () => page.locator('#review-result').waitFor();
  const leaveDraft = async () => {
    await page.getByRole('link',{name:'Cancel',exact:true}).click();
    await page.getByRole('dialog').getByRole('button',{name:'Leave without saving',exact:true}).click();
    await page.getByRole('heading',{name:'Service-account assurance review',exact:true}).waitFor();
  };
  const assess = async (id, choice, notes, view='outstanding') => {
    await page.goto(`${origin}/population-review/reviews/1/inputs/${id}/assessment?view=${view}`);
    await formReady();
    await choose(choice);
    await basis().fill(notes);
    await save().click();
    await saved();
  };
  await page.goto(origin + '/population-review/reviews/1');
  assert(await page.getByRole('button',{name:'Start review',exact:true}).isVisible(), 'Opening does not capture scope');
  await page.getByRole('button',{name:'Start review',exact:true}).click();
  await saved();
  assert(await page.locator('tbody tr').count() === 4, 'Start captures the eligible population');
  const captured = await page.locator('time').first().getAttribute('datetime');
  await scenario('add');
  await post('/population-review/reviews/1/start', {});
  await page.reload();
  assert(await page.locator('tbody tr').count() === 4 && await page.locator('time').first().getAttribute('datetime') === captured, 'Later additions and repeated Start do not recapture');
  const outstandingView = page.getByRole('navigation',{name:'Review views'}).getByRole('link',{name:/Outstanding/});
  await outstandingView.click();
  await outstandingView.and(page.locator('[aria-current="page"]')).waitFor();
  await page.getByRole('link',{name:'Continue review',exact:true}).click();
  await choose('satisfactory');
  await basis().fill(' ');
  await save().click();
  await page.getByText("Notes can't be blank",{exact:true}).waitFor();
  assert(await outcome().inputValue() === 'satisfactory', 'Server validation retains attempted outcome');
  await basis().fill('Independent access export confirms ownership and safeguards.');
  await scenario('failure');
  await save().click();
  await page.getByText(/The save service is temporarily unavailable/).waitFor();
  assert(await basis().inputValue() === 'Independent access export confirms ownership and safeguards.', '503 retains explanation');
  const retry = await formValues();
  await save().click();
  await saved();
  assert(new URL(page.url()).searchParams.get('view') === 'outstanding' && await page.locator('tbody tr').count() === 3, 'Saved subject leaves the retained Outstanding view');
  assert(await page.locator('#review-result').evaluate(el => document.activeElement === el), 'Successful return focuses acknowledgement');
  await page.getByRole('link',{name:'Read saved result',exact:true}).click();
  await page.getByRole('heading',{name:'Satisfactory',exact:true}).waitFor();
  assert(await page.getByRole('heading',{name:'Satisfactory',exact:true}).count() === 1, 'Filtered-out result is directly accessible');
  const duplicate = await post('/population-review/reviews/1/inputs/1/assessment', retry);
  assert(duplicate.status === 200 && duplicate.text.includes('already recorded'), 'Duplicate successful POST acknowledges previous result');
  await page.reload();
  assert(await page.getByRole('heading',{name:'Satisfactory',exact:true}).count() === 1, 'Duplicate creates no second assessment');
  await page.goto(origin + '/population-review/reviews/1?view=completed');
  await page.locator('#subject-1').getByRole('link',{name:'View assessment: Backup automation',exact:true}).click();
  await page.getByRole('heading',{name:'Latest assessment',exact:true}).waitFor();
  assert(await page.locator('#review-entry').count() === 0 && await page.getByRole('link',{name:'Record new assessment',exact:true}).isVisible(), 'Viewing a finished assessment keeps recording a new event explicit');
  checks.push('explicit capture, later-addition isolation, 422/503 retention, filtered return/focus, read-only results and deduplication');

  await page.goto(origin + '/population-review/reviews/1/inputs/1/assessment?view=changed');
  await formReady();
  await basis().fill('Unsaved reassessment explanation.');
  await page.getByRole('link',{name:'Cancel',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'Keep editing',exact:true}).click();
  assert(await basis().inputValue() === 'Unsaved reassessment explanation.', 'Keep editing retains draft');
  assert(await page.getByRole('link',{name:'Cancel',exact:true}).evaluate(el => el === document.activeElement), 'Canceled exit restores focus');
  await scenario('change');
  await save().click();
  await page.getByText(/The review or supporting facts changed/).waitFor();
  assert(await basis().inputValue() === 'Unsaved reassessment explanation.', '409 retains stale assessment draft');
  assert(await save().isDisabled(), 'Stale assessment offered an impossible retry');
  await leaveDraft();
  await page.goto(origin + '/population-review/reviews/1?view=changed');
  assert(await page.locator('tbody tr').count() === 1 && (await page.locator('tbody').innerText()).includes('Changed facts'), 'Changed facts are outstanding and have a dedicated view');
  await assess(1, 'satisfactory', 'Rechecked the changed owner against the operating evidence.', 'changed');
  await page.getByRole('heading',{name:'No accounts in this view',exact:true}).waitFor();
  await page.getByRole('link',{name:'Read saved result',exact:true}).click();
  await page.getByRole('region',{name:/^Earlier assessments/}).getByRole('heading',{name:'Satisfactory',exact:true}).waitFor();
  assert(await page.getByRole('heading',{name:'Satisfactory',exact:true}).count() === 2, 'Reassessment preserves prior results');
  assert((await page.locator('main').innerText()).includes('Robin Ellis') && (await page.locator('main').innerText()).includes('Jamie Chen'), 'Each assessment retains its own source facts');
  checks.push('canceled exit/focus, stale-save draft retention, changed-fact filtering and preserved earlier facts');

  await assess(2, 'discrepancy', 'Release account has excessive permissions.');
  assert((await page.locator('#subject-2').innerText()).includes('Finding required'), 'Discrepancy blocks readiness until linked treatment');
  await page.goto(origin + '/population-review/reviews/1/completion');
  assert(await page.getByRole('button',{name:'Complete review',exact:true}).isDisabled(), 'Completion explains blockers and is disabled');
  await page.getByLabel('Review conclusion',{exact:true}).fill('Attempt to bypass readiness.');
  const premature = await post('/population-review/reviews/1/complete', await formValues());
  assert(premature.status === 409 && premature.text.includes('outstanding work'), 'Server rejects forced completion regardless of UI');
  await leaveDraft();
  await page.goto(origin + '/population-review/reviews/1/inputs/2/finding?view=outstanding');
  await page.getByLabel('Treatment owner',{exact:true}).fill('Sam Rivera');
  await page.getByLabel('Finding and treatment plan',{exact:true}).fill('Remove excessive permissions through an authorized access request.');
  await page.getByRole('button',{name:'Record finding',exact:true}).click();
  await saved();
  await assess(3, 'excluded', 'Independent inventory confirms that this integration was decommissioned.');
  await assess(4, 'satisfactory', 'Confirmed provider export safeguards with its owner.');
  assert(await page.getByRole('heading',{name:'No accounts in this view',exact:true}).isVisible(), 'Last save retains the empty Outstanding view');
  assert(await count(page, 'Excluded') === '1' && await count(page, 'Open findings') === '1', 'Exclusions and open treatment have separate counts');
  checks.push('actionable completion blockers, server readiness enforcement, linked treatment and explained exclusion');

  await page.getByRole('link',{name:'Complete review',exact:true}).click();
  await page.getByLabel('Review conclusion',{exact:true}).fill('Checking complete; the assigned permission finding remains open.');
  await scenario('change');
  await page.getByRole('button',{name:'Complete review',exact:true}).click();
  await page.getByText(/The review or supporting facts changed/).waitFor();
  assert(await page.getByLabel('Review conclusion',{exact:true}).inputValue() === 'Checking complete; the assigned permission finding remains open.', 'Stale completion retains conclusion');
  assert(await page.getByRole('button',{name:'Complete review',exact:true}).isDisabled(), 'Stale conclusion offered an impossible retry');
  await leaveDraft();
  await assess(1, 'satisfactory', 'Owner change rechecked before completion.');
  await page.getByRole('link',{name:'Complete review',exact:true}).click();
  await page.getByLabel('Review conclusion',{exact:true}).fill('Checking complete; the assigned permission finding remains open.');
  await page.getByRole('button',{name:'Complete review',exact:true}).click();
  await saved();
  assert((await page.locator('main').innerText()).includes('Open findings keep their own follow-up.'), 'Completed review retains open treatment');
  await scenario('change');
  await page.reload();
  await page.getByRole('navigation',{name:'Review views'}).getByRole('link',{name:/All accounts/}).click();
  assert(!(await page.locator('tbody').innerText()).includes('Changed facts'), 'Later source changes do not invalidate completed results');
  await page.getByRole('link',{name:'Account reviews',exact:true}).last().click();
  await page.goBack();
  assert((await page.locator('main').innerText()).includes('Completed'), 'Turbo return shows authoritative completed state');
  checks.push('stale-completion recovery, immutable completed assessments, open follow-up and Turbo return');

  const nativeContext = await page.context().browser().newContext({javaScriptEnabled:false});
  try {
    const native = await nativeContext.newPage();
    await native.goto(origin + '/population-review/reviews/2');
    await native.getByRole('button',{name:'Start review',exact:true}).click();
    await native.getByRole('link',{name:'Complete review',exact:true}).click();
    await native.getByLabel('Coverage and conclusion',{exact:true}).fill(' ');
    await native.getByRole('button',{name:'Complete review',exact:true}).click();
    await native.getByText("Notes can't be blank",{exact:true}).waitFor();
    await native.getByLabel('Coverage and conclusion',{exact:true}).fill('Checked the satellite operating inventory and confirmed no service accounts operate in this office.');
    await native.getByRole('button',{name:'Complete review',exact:true}).click();
    await native.locator('#review-result').waitFor();
    assert((await native.locator('main').innerText()).includes('Completed'), 'Native empty-population completion requires coverage');
    await native.goto(origin + '/population-review/reviews/1');
    await native.getByRole('button',{name:'Start review',exact:true}).click();
    await native.getByRole('link',{name:'Continue review',exact:true}).click();
    await native.getByRole('radio',{name:/Satisfactory/}).check();
    await native.getByLabel('Assessment basis',{exact:true}).fill('Native assessment against independent operating evidence.');
    await native.getByRole('button',{name:'Save assessment',exact:true}).click();
    await native.locator('#review-result').waitFor();
    assert(await count(native, 'Reviewed') === '1', 'Native assessment records and returns successfully');
    assert(await native.getByRole('list',{name:'Review activity, newest first'}).isVisible(), 'Recorded events are missing from the native review page');
    await native.getByRole('link',{name:'Read saved result',exact:true}).click();
    assert(await native.getByRole('region',{name:'Account facts at review start'}).getByText('Captured',{exact:true}).isVisible(), 'Capture context is missing from the native result page');
  } finally { await nativeContext.close(); }
  checks.push('native server-rendered assessment and evidenced empty-population validation/completion');
  assert(errors.length === 0, 'No uncaught browser errors: ' + errors.join('; '));
  return {passed:true, checks};
}
